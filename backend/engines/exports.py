TYPE_COLORS = {"stage": "#8e44ad", "mandap": "#c0392b", "seating": "#2980b9", "dining": "#27ae60", "buffet": "#d35400", "dance_floor": "#e84393",
               "activity": "#16a085", "reg_desk": "#7f8c8d", "photo_booth": "#f39c12", "first_aid": "#e74c3c", "kitchen": "#95a5a6", "backstage": "#34495e"}


def _inr(p: int) -> str:
    from .money import fmt_inr
    return fmt_inr(p).replace("₹", "Rs ")      # built-in PDF fonts have no rupee glyph


def pdf_report(plan: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                            title=f"EventForge plan - {plan['name']}")
    ss = getSampleStyleSheet()
    H1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=20, textColor=colors.HexColor("#7a1f2b"), alignment=0)
    H2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=13, textColor=colors.HexColor("#7a1f2b"), spaceBefore=10)
    N = ParagraphStyle("n", parent=ss["BodyText"], fontSize=9, leading=12)
    S = ParagraphStyle("s", parent=N, fontSize=7.5, textColor=colors.HexColor("#666666"))
    sp, b, t, ov = plan["spec"], plan["budget"], plan["timeline"], plan["overview"]
    el = [Paragraph(f"EventForge — {plan['name']}", H1),
          Paragraph(f"{sp['event_type'].title()} · {sp['city']} · {sp['date']} · {sp['guests']} guests · {sp['days']} day(s) · budget {_inr(sp['budget_paise'])}", N),
          Paragraph("Planning document generated by EventForge. Costs are planning estimates (assumptions), vendors are sample data, and the venue preview is not proof of real dimensions or safety.", S)]
    el += [Paragraph("Summary", H2)]
    data = [["Days to event", str(ov["days_to_event"]), "Timeline", t.get("status", "")],
            ["Expected cost", _inr(b["estimate_total"]["exp"]), "Chance of exceeding budget (simulated)", f"{b['risk']['p_exceed_budget'] * 100:.0f}%"],
            ["Verification", f"{plan['critic']['hard_passed']}/{plan['critic']['hard_total']} checks passed", "Venue (layout)", ov["venue"]]]
    tb = Table(data, colWidths=[32 * mm, 45 * mm, 55 * mm, 42 * mm])
    tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8.5), ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc")),
                            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f6efe6")), ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f6efe6"))]))
    el.append(tb)
    el.append(Paragraph("Budget", H2))
    rows = [["Category", "Allocated", "Expected", "Status", "Why"]]
    for r in b["categories"]:
        rows.append([r["label"], _inr(r["allocated"]), _inr(r["estimate"]["exp"]), r["status"], Paragraph(r["why"][:110], S)])
    rows.append(["Contingency (%d%%)" % b["contingency_pct"], _inr(b["contingency"]), "", "", Paragraph(b["contingency_why"], S)])
    rows.append(["TOTAL", _inr(b["total"]), _inr(b["estimate_total"]["exp"]), b["feasibility"], ""])
    tb = Table(rows, colWidths=[40 * mm, 27 * mm, 27 * mm, 16 * mm, 72 * mm], repeatRows=1)
    tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#7a1f2b")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                            ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold")]))
    el.append(tb)
    risk = b["risk"]
    el.append(Paragraph(f"Risk simulation: {risk['n']:,} runs · P50 {_inr(risk['percentiles'][50])} · P90 {_inr(risk['percentiles'][90])} · "
                        f"{risk['p_exceed_budget'] * 100:.0f}% chance of exceeding the total budget. {risk['label']}.", S))
    el.append(Paragraph("Timeline (critical tasks marked *)", H2))
    rows = [["Task", "Start", "Finish", "Latest", "Slack", "Risk"]]
    for x in t.get("tasks", []):
        rows.append([("* " if x["critical"] else "") + x["name"][:58], x["start"], x["end"], x["latest_finish"], str(x["slack"]), x["risk"]])
    tb = Table(rows, colWidths=[84 * mm, 21 * mm, 21 * mm, 21 * mm, 12 * mm, 15 * mm], repeatRows=1)
    tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 7.5), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#7a1f2b")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                            ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc")), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#faf6f0")])]))
    el.append(tb)
    el.append(PageBreak())
    el.append(Paragraph("Vendors (SAMPLE data — estimates only)", H2))
    if plan["selection"]:
        rows = [["Category", "Selected vendor", "Est. price", "Score"]] + [[c, r["vendor"]["name"], _inr(r["price_estimate"]["mid"]), str(r["score"])] for c, r in plan["selection"].items()]
        tb = Table(rows, colWidths=[35 * mm, 80 * mm, 35 * mm, 20 * mm])
        tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc"))]))
        el.append(tb)
    else:
        el.append(Paragraph("No vendors selected yet. Top-ranked per category:", N))
        rows = [["Category", "Top candidate", "Est. price", "Score"]] + [[c, r["ranked"][0]["vendor"]["name"], _inr(r["ranked"][0]["price_estimate"]["mid"]), str(r["ranked"][0]["score"])]
                                                                     for c, r in plan["vendors"].items() if r["ranked"]]
        tb = Table(rows, colWidths=[35 * mm, 80 * mm, 35 * mm, 20 * mm])
        tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc"))]))
        el.append(tb)
    el.append(Paragraph("Programs", H2))
    rows = [["Day", "Time", "Program", "Zone"]] + [[str(p["day"]), f"{p['start']}-{p['end']}", p["name"], p["zone_label"]] for p in plan["programs"]]
    tb = Table(rows, colWidths=[12 * mm, 28 * mm, 100 * mm, 35 * mm], repeatRows=1)
    tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc"))]))
    el.append(tb)
    # layout drawing
    vis = plan["vision"]
    L, v = vis["layout"], vis["venue"]
    el.append(Paragraph(f"Venue layout — {v['name']} ({v['width']} × {v['depth']} m) · theme: {L['theme']['name']}", H2))
    scale = min(170 * mm / v["width"], 95 * mm / v["depth"])
    d = Drawing(v["width"] * scale + 4, v["depth"] * scale + 4)
    d.add(Rect(2, 2, v["width"] * scale, v["depth"] * scale, strokeColor=colors.HexColor("#333333"), fillColor=colors.HexColor("#fbf8f1")))
    shared = L["params"].get("shared")
    for e in L["elements"]:
        if shared and e["type"] == "seating":
            continue
        c = colors.HexColor(TYPE_COLORS.get(e["type"], "#999999"))
        d.add(Rect(2 + e["x"] * scale, 2 + (v["depth"] - e["y"] - e["h"]) * scale, e["w"] * scale, e["h"] * scale, strokeColor=c, fillColor=c, fillOpacity=.35, strokeWidth=.8))
        d.add(String(2 + e["x"] * scale + 2, 2 + (v["depth"] - e["y"] - e["h"] / 2) * scale - 3, ("Shared floor: chairs / dining" if shared and e["type"] == "dining" else e["label"])[:30], fontSize=6, fillColor=colors.HexColor("#222222")))
    el.append(d)
    el.append(Paragraph("Planning preview — not proof that the real venue is safe or that its dimensions match. North is at the top; the main entrance is at the bottom.", S))
    el.append(Paragraph("Verification", H2))
    rows = [["Check", "Status", "Evidence"]]
    for h in plan["critic"]["hard"]:
        rows.append([Paragraph(h["title"], S), h["status"].upper(), Paragraph(h["evidence"][:140], S)])
    tb = Table(rows, colWidths=[70 * mm, 16 * mm, 90 * mm], repeatRows=1)
    tb.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 7.5), ("GRID", (0, 0), (-1, -1), .25, colors.HexColor("#cccccc")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el.append(tb)
    if plan["critic"]["risks"]:
        el.append(Paragraph("Risk findings (heuristic)", H2))
        for r in plan["critic"]["risks"][:10]:
            el.append(Paragraph(f"<b>[{r['severity'].upper()}] {r['title']}</b> — {r['evidence']} <i>Fix: {r['fix']}</i>", N))
    doc.build(el)
    return buf.getvalue()


