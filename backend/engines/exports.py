def _font(size):
    for f in ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/dejavu/DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(f, size)
        except Exception:
            pass
    return ImageFont.load_default()


def walkthrough_gif(plan: dict, fps_frames: int = 10) -> bytes:
    """Server-side fallback 'video': top-down animated walkthrough along each scene's computed route."""
    vis = plan["vision"]
    L, v, scenes = vis["layout"], vis["venue"], [s for s in vis["scenes"] if s.get("zone")]
    Wp, Hp = 640, 420
    pad, top = 16, 38
    sc = min((Wp - 2 * pad) / v["width"], (Hp - top - 46) / v["depth"])
    ox, oy = pad + ((Wp - 2 * pad) - v["width"] * sc) / 2, top
    pal = L["theme"]["palette"]
    f_big, f_sm = _font(15), _font(12)

    def base(scene):
        im = Image.new("RGB", (Wp, Hp), "#faf6ef")
        d = ImageDraw.Draw(im)
        night = scene["lighting"] in ("evening", "night")
        d.rectangle([ox, oy, ox + v["width"] * sc, oy + v["depth"] * sc], fill="#2b2230" if night else "#fff9ee", outline="#444")
        shared = L["params"].get("shared")
        for e in L["elements"]:
            if shared and e["type"] == "seating":
                continue
            col = TYPE_COLORS.get(e["type"], "#999")
            active = scene["zone"]["id"] == e["id"] or (shared and scene["zone"]["id"] == "seating" and e["type"] == "dining")
            x0, y0 = ox + e["x"] * sc, oy + e["y"] * sc
            d.rectangle([x0, y0, x0 + e["w"] * sc, y0 + e["h"] * sc], fill=col if active else None, outline=col, width=3 if active else 1)
            d.text((x0 + 3, y0 + 2), ("Shared floor (chairs / dining)" if shared and e["type"] == "dining" else e["label"])[:30], fill="#ffffff" if (active or night) else "#333", font=f_sm)
        for o in v["obstacles"]:
            d.ellipse([ox + o["x"] * sc, oy + o["y"] * sc, ox + (o["x"] + o["w"]) * sc, oy + (o["y"] + o["h"]) * sc], fill="#7d8f69")
        for dr in v["doors"]:
            from .vision import _door_point
            px, py = _door_point(v, dr)
            d.ellipse([ox + px * sc - 5, oy + py * sc - 5, ox + px * sc + 5, oy + py * sc + 5], fill="#2e7d32" if dr["kind"] == "entrance" else "#c62828")
        d.rectangle([0, 0, Wp, 30], fill=pal[0])
        d.text((10, 6), f"{plan['name']} — {L['theme']['name']}", fill="#ffffff", font=f_big)
        d.rectangle([0, Hp - 40, Wp, Hp], fill="#1f1f1f")
        d.text((10, Hp - 32), scene["caption"][:92], fill="#ffffff", font=f_sm)
        d.text((10, Hp - 17), "Planning preview — not an exact representation of the venue", fill="#bbbbbb", font=_font(10))
        return im

    frames, durs = [], []
    for sc_ in scenes:
        b0 = base(sc_)
        route = sc_["route"]
        pts = []
        for i in range(len(route) - 1):
            for k in range(fps_frames):
                t = k / fps_frames
                pts.append((route[i][0] + (route[i + 1][0] - route[i][0]) * t, route[i][1] + (route[i + 1][1] - route[i][1]) * t))
        pts.append(tuple(route[-1]))
        step = max(1, len(pts) // 14)
        for i in range(0, len(pts), step):
            im = b0.copy()
            d = ImageDraw.Draw(im)
            trail = [(ox + p[0] * sc, oy + p[1] * sc) for p in pts[:i + 1]]
            if len(trail) > 1:
                d.line(trail, fill=pal[1], width=3)
            x, y = trail[-1]
            d.ellipse([x - 6, y - 6, x + 6, y + 6], fill=pal[0], outline="#ffffff", width=2)
            frames.append(im.convert("P", palette=Image.ADAPTIVE, colors=64))
            durs.append(110)
        durs[-1] = 1100
    if not frames:
        frames = [Image.new("P", (Wp, Hp))]
        durs = [500]
    out = io.BytesIO()
    frames[0].save(out, format="GIF", save_all=True, append_images=frames[1:], duration=durs, loop=0, optimize=True)
    return out.getvalue()
