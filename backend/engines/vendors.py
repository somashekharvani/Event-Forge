DEFAULT_WEIGHTS = {"budget": .30, "rating": .20, "distance": .10, "availability": .25, "fit": .15}


def _fit_score(v: dict, spec: EventSpec) -> tuple[float, list[str]]:
    s, notes = .5, []
    tags = set(v["tags"])
    if v["category"] == "caterer":
        if spec.diet in ("veg", "jain") and "veg_only" in tags:
            s += .3; notes.append("veg-only kitchen matches your diet")
        if spec.diet == "jain" and "jain_menu" in tags:
            s += .2; notes.append("has Jain menu")
        if spec.diet == "nonveg" and "veg_only" in tags:
            s -= .4; notes.append("veg-only — doesn't match non-veg menu")
        if spec.culture == "kannada" and "south_indian" in tags:
            s += .1; notes.append("south-Indian speciality")
        if spec.culture == "north_indian" and "north_indian" in tags:
            s += .1
    if v["category"] == "venue":
        if spec.outdoor and "outdoor" in tags:
            s += .25; notes.append("outdoor space available")
        if spec.outdoor and "rain_cover" in tags:
            s += .15; notes.append("rain cover")
        if spec.outdoor is False and "ac" in tags:
            s += .25; notes.append("air-conditioned")
        if "generator_backup" in tags:
            s += .1; notes.append("generator backup")
        if spec.guests > 200 and "parking" in tags:
            s += .1; notes.append("parking")
    if v["category"] == "entertainment":
        if "loud music" in spec.avoid:
            s += .3 if "acoustic" in tags or "classical" in tags else -.35
            notes.append("quiet-friendly" if "acoustic" in tags or "classical" in tags else "loud act conflicts with 'avoid loud music'")
        if spec.event_type == "birthday" and (spec.celebrant_age or 30) <= 12 and "kids_acts" in tags:
            s += .3; notes.append("kids' acts")
    if v["category"] == "priest" and spec.culture in tags:
        s += .4; notes.append(f"{spec.culture} rituals")
    if v["category"] == "decorator" and "eco_friendly" in tags and "firecrackers" in spec.avoid:
        s += .2; notes.append("eco-friendly")
    return max(0.0, min(1.0, s)), notes


def rank_vendors(spec: EventSpec, category: str, allocation_paise: int, weights: dict | None = None,
                 limit: int = 8) -> dict:
    w = dict(DEFAULT_WEIGHTS)
    if weights:
        w.update({k: float(v) for k, v in weights.items() if k in w})
    tot = sum(w.values()) or 1
    w = {k: v / tot for k, v in w.items()}
    rows = []
    for v in all_vendors(spec.city):
        if v["category"] != category:
            continue
        price = price_for_event(v, spec)
        avail = is_available(v, spec.date, spec.days) if spec.date else True
        ratio = price["mid"] / allocation_paise if allocation_paise else 9
        budget_fit = 1.0 if ratio <= .85 else max(0.0, 1 - (ratio - .85) / .45)
        rating = max(0.0, min(1.0, (v["rating"] - 3.5) / 1.4))
        dist = 1 - min(v["distance_km"] / 25, 1)
        fit, notes = _fit_score(v, spec)
        comp = {"budget": budget_fit, "rating": rating, "distance": dist, "availability": 1.0 if avail else 0.0, "fit": fit}
        score = sum(comp[k] * w[k] for k in w)
        eligible, reasons = True, []
        if category == "venue":
            if v["capacity"] < spec.guests:
                eligible = False
                reasons.append(f"capacity {v['capacity']} < {spec.guests} guests")
            elif v["capacity"] > spec.guests * 3:
                reasons.append("much larger than needed (higher cost, emptier room)")
        if not avail:
            reasons.append("sample calendar shows this date as booked")
        if category == "caterer" and v.get("min_guests", 0) > spec.guests:
            reasons.append(f"minimum {v['min_guests']} guests")
        rows.append({
            "vendor": {k: v[k] for k in ("id", "name", "category", "city", "rating", "distance_km", "tags", "sample", "price_model") if k in v}
                      | ({"capacity": v["capacity"]} if "capacity" in v else {}),
            "price_estimate": price, "available": avail, "eligible": eligible, "notes": notes + reasons,
            "components": {k: round(comp[k], 3) for k in comp},
            "contributions": {k: round(comp[k] * w[k] * 100, 1) for k in comp},
            "score": round(score * 100, 1) if eligible else 0.0,
            "over_allocation": price["mid"] > allocation_paise,
        })
    rows.sort(key=lambda r: (-r["score"], -r["vendor"]["rating"]))
    eligible_available = [r for r in rows if r["eligible"] and r["available"]]
    return {"category": category, "label": CATEGORY_LABEL[category], "weights": {k: round(v, 3) for k, v in w.items()},
            "allocation": allocation_paise, "ranked": rows[:limit], "count": len(rows),
            "backup_count": max(0, len(eligible_available) - 1),
            "disclaimer": "SAMPLE data: names, ratings, prices and availability are synthetic. Treat all prices as estimates until you hold a written quote."}


