def extract_quote(text: str, label: str = "Quote", guests: int | None = None) -> dict:
    """Structured extraction from pasted quote text. Never invents values: missing fields are flagged."""
    t = text.replace("₹", "₹")
    low = t.lower()

    def money(s: str) -> int | None:
        m = re.search(r"(\d[\d,]*(?:\.\d+)?)\s*(lakh|lac|l|k)?", s.lower().replace(",", "") if False else s.lower())
        if not m:
            return None
        v = float(m.group(1).replace(",", ""))
        v *= {"lakh": 1e5, "lac": 1e5, "l": 1e5, "k": 1e3}.get(m.group(2) or "", 1)
        return to_paise(v)

    f: dict = {}
    # total
    m = re.search(r"(?:grand\s*total|total(?:\s*amount)?|package(?:\s*price)?|quote(?:d)?(?:\s*price)?)\s*[:\-–=]?\s*(?:rs\.?|inr|₹)?\s*([\d,]+(?:\.\d+)?\s*(?:lakh|lac|l|k)?)", low)
    if m:
        f["total"] = {"value": money(m.group(1)), "evidence": m.group(0).strip()}
    else:
        amts = [(money(x), x) for x in re.findall(r"(?:₹|rs\.?|inr)\s*([\d,]+(?:\.\d+)?\s*(?:lakh|lac|l|k)?)", low)]
        amts = [a for a in amts if a[0]]
        if amts:
            top = max(amts, key=lambda a: a[0])
            f["total"] = {"value": top[0], "evidence": f"largest amount found: ₹{top[1]}"}
    # per-head
    m = re.search(r"(?:₹|rs\.?|inr)?\s*([\d,]+)\s*(?:/|per)\s*(?:plate|head|person|guest|pax)", low)
    if m:
        f["per_head"] = {"value": to_paise(int(m.group(1).replace(",", ""))), "evidence": m.group(0).strip()}
    # GST
    m = re.search(r"gst[^\d%,]{0,12}(\d{1,2})\s*%", low) or re.search(r"(\d{1,2})\s*%\s*gst", low)
    if m:
        f["gst_pct"] = {"value": int(m.group(1)), "evidence": m.group(0).strip()}
    f["gst_included"] = None
    if re.search(r"(?:inclusive of|incl\.?|including|includes?)\s*(?:all\s*)?(?:taxes|gst)|taxes included|gst included|\+?\s*gst\s*included", low):
        f["gst_included"] = True
    elif re.search(r"(?:exclusive of|excl\.?|excluding|plus|\+)\s*(?:applicable\s*)?(?:taxes|gst)|gst\s*extra|gst\s*(?:not included|additional)", low):
        f["gst_included"] = False
    # advance
    m = re.search(r"advance[^\d]{0,15}(\d{1,3})\s*%", low) or re.search(r"(\d{1,3})\s*%\s*advance", low)
    if m:
        f["advance_pct"] = {"value": int(m.group(1)), "evidence": m.group(0).strip()}
    else:
        m = re.search(r"advance[^\d₹]{0,15}(?:₹|rs\.?|inr)\s*([\d,]+)", low)
        if m:
            f["advance_amount"] = {"value": to_paise(int(m.group(1).replace(",", ""))), "evidence": m.group(0).strip()}
    # cancellation / overtime / validity / inclusions / exclusions
    for key, pat in {
        "cancellation": r"[^.\n]*(?:cancell?ation|refund)[^.\n]*", "overtime": r"[^.\n]*(?:overtime|extra hour|additional hour)[^.\n]*",
        "validity": r"[^.\n]*(?:valid (?:till|until|for)|validity)[^.\n]*", "payment_terms": r"[^.\n]*(?:balance|milestone|installment|installments)[^.\n]*"}.items():
        mm = re.search(pat, low)
        if mm:
            f[key] = {"value": mm.group(0).strip(), "evidence": mm.group(0).strip()}
    inc = re.search(r"(?:includes?|inclusions?|inclusive of|package includes)[:\s]+([^\n]+)", t, re.I)
    exc = re.search(r"(?:excludes?|exclusions?|not included|extra charges? for)[:\s]+([^\n]+)", t, re.I)
    f["inclusions"] = [x.strip() for x in re.split(r",|;|\band\b", inc.group(1)) if x.strip()] if inc else []
    f["exclusions"] = [x.strip() for x in re.split(r",|;|\band\b", exc.group(1)) if x.strip()] if exc else []

    required = {"total": "total price", "gst_pct": "GST rate", "advance": "advance/payment terms", "cancellation": "cancellation policy",
                "overtime": "overtime charges", "inclusions": "inclusions list", "validity": "quote validity"}
    missing = []
    if "total" not in f and "per_head" not in f:
        missing.append(required["total"])
    if "gst_pct" not in f and f["gst_included"] is None:
        missing.append(required["gst_pct"])
    if "advance_pct" not in f and "advance_amount" not in f:
        missing.append(required["advance"])
    for k in ("cancellation", "overtime", "validity"):
        if k not in f:
            missing.append(required[k])
    if not f["inclusions"]:
        missing.append(required["inclusions"])
    out = {"label": label, "fields": f, "missing": missing, "completeness": round(1 - len(missing) / 7, 2)}
    # normalised total
    tot = f.get("total", {}).get("value")
    if "per_head" in f and guests and (not tot or tot <= f["per_head"]["value"] * 1.01):
        tot = f["per_head"]["value"] * int(guests)
        f["total"] = {"value": tot, "evidence": f"per-head {f['per_head']['evidence']} × {guests} guests (computed)"}
        out["note"] = "Total computed from the per-head rate and your guest count."
    elif "per_head" in f and not guests and tot and tot <= f["per_head"]["value"] * 1.01:
        tot = None
        out["note"] = "Only a per-head rate was found; guest count is needed to compute a total."
    if tot:
        if f["gst_included"] is True:
            out["total_incl_gst"] = tot
            out["gst_note"] = "GST stated as included."
        elif "gst_pct" in f:
            out["total_incl_gst"] = tot + tot * f["gst_pct"]["value"] // 100
            out["gst_note"] = f"Added stated GST {f['gst_pct']['value']}%."
        else:
            out["total_incl_gst_range"] = [tot + tot * 5 // 100, tot + tot * 18 // 100]
            out["gst_note"] = "GST not stated: range assumes 5%–18% (assumption — ask the vendor)."
    return out


def compare_quotes(quotes: list[dict]) -> dict:
    rows = []
    for q in quotes:
        total = q.get("total_incl_gst") or (sum(q["total_incl_gst_range"]) // 2 if q.get("total_incl_gst_range") else None)
        rows.append({"label": q["label"], "total_normalised": total, "exact": "total_incl_gst" in q, "missing": q["missing"],
                     "completeness": q["completeness"], "advance": q["fields"].get("advance_pct", {}).get("value"),
                     "has_cancellation_terms": "cancellation" in q["fields"], "inclusions": q["fields"]["inclusions"],
                     "exclusions": q["fields"]["exclusions"]})
    priced = [r for r in rows if r["total_normalised"]]
    best = None
    if priced:
        # transparent: price rank (70%) + completeness (30%); hidden-cost risk is penalised through completeness
        lo, hi = min(r["total_normalised"] for r in priced), max(r["total_normalised"] for r in priced)
        for r in priced:
            price_score = 1.0 if hi == lo else 1 - (r["total_normalised"] - lo) / (hi - lo)
            r["value_score"] = round(100 * (.7 * price_score + .3 * r["completeness"]), 1)
        best = max(priced, key=lambda r: r["value_score"])["label"]
    return {"rows": rows, "best_value": best,
            "note": "Value score = 70% normalised price + 30% completeness of terms. Missing fields = possible hidden costs: ask before comparing."}
