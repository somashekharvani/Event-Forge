def all_vendors(city: str) -> list[dict]:
    c = geo.canon_city(city) or city
    if c not in _CACHE:
        _CACHE[c] = _gen_city(c)
    return _CACHE[c]


def is_available(v: dict, date: dt.date, days: int = 1) -> bool:
    b = set(v["booked_dates"])
    return not any((date + dt.timedelta(days=i)).isoformat() in b for i in range(days))


def price_for_event(v: dict, spec: EventSpec) -> dict:
    """Estimated cost in paise for this event, as (low, mid, high). Estimate only."""
    pm = v["price_model"]
    if pm == "per_head_per_meal":
        meals = (1 + .75 * (spec.days - 1) + .25) if spec.event_type == "wedding" else 1.0
        units = spec.guests * meals * (.85 if spec.event_type == "community" else 1.0)
    elif pm == "flat_per_day":
        units = spec.days
    else:
        units = 1
    lo, hi = to_paise(v["price_low"] * units), to_paise(v["price_high"] * units)
    return {"low": lo, "mid": (lo + hi) // 2, "high": hi, "units": round(units, 2), "model": pm}


