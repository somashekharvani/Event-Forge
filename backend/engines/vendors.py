def outreach(v: dict, spec: EventSpec, channel: str = "whatsapp", lang: str = "en", contact: str = "") -> dict:
    cat = v["category"]
    date = spec.date.strftime("%d %b %Y") if spec.date else "TBD"
    when = date + (f" ({spec.days} days)" if spec.days > 1 else "")
    ev = {"wedding": "wedding", "birthday": "birthday celebration", "community": "community event"}[spec.event_type]
    top = checklist_for(cat, spec)["questions"][:4]
    name = v["name"].replace(" (sample)", "")
    if lang == "hi":
        body = (f"नमस्ते {name} जी,\n\nहम {spec.city} में {when} को एक {ev} आयोजित कर रहे हैं (लगभग {spec.guests} मेहमान)। "
                f"क्या आप इस तारीख़ के लिए उपलब्ध हैं? कृपया अपना लिखित कोटेशन (GST सहित) भेजें और ये बातें बताएँ:\n" +
                "\n".join(f"{i + 1}. {q}" for i, q in enumerate(top)) + "\n\nधन्यवाद।")
        subject = f"{ev} — {when} — कोटेशन अनुरोध"
    else:
        body = (f"Hello {name},\n\nWe're planning a {ev} in {spec.city} on {when} for about {spec.guests} guests "
                f"(budget-conscious, diet: {spec.diet.replace('_', ' ')}). Are you available on this date? "
                f"Could you share a written quote including GST and answer:\n" +
                "\n".join(f"{i + 1}. {q}" for i, q in enumerate(top)) + "\n\nThank you!")
        subject = f"Availability & quote request — {ev} on {when}"
    if channel == "email":
        return {"channel": "email", "subject": subject, "body": body, "to": contact,
                "mailto": f"mailto:{contact}?subject={subject}&body={body}".replace("\n", "%0A").replace(" ", "%20")}
    import urllib.parse
    return {"channel": "whatsapp", "body": body,
            "link": f"https://wa.me/{re.sub(r'[^0-9]', '', contact)}?text={urllib.parse.quote(body)}" if contact else "",
            "note": "Add the vendor's phone number to get a tap-to-send link."}


