def checklist_for(category: str, spec: EventSpec) -> dict:
    c = {k: list(v) if isinstance(v, list) else v for k, v in CHECKLISTS[category].items()}
    extra = []
    if category == "caterer" and spec.diet in ("veg", "jain", "mostly_veg"):
        extra.append("Confirm separate preparation/serving for veg items if any non-veg is served.")
    if category == "venue" and spec.guests > 400:
        extra.append("Confirm parking capacity and crowd entry/exit width for 400+ guests.")
    if category == "venue" and spec.event_type == "community":
        extra.append("Ask which municipal/police permissions the venue already holds vs which you must apply for.")
    c["questions"] += extra
    c["items"] = [{"id": f"{category}-{i}", "text": q} for i, q in enumerate(c["questions"])]
    return {"category": category, "label": CATEGORY_LABEL[category], **c}


